    // Helper to ensure no duplicates in lists
    private static List<String> uniqueList(String... words) {
        Set<String> uniqueSet = new HashSet<>(Arrays.asList(words));
        List<String> list = new ArrayList<>(uniqueSet);
        Collections.shuffle(list); // Shuffle now so every game load is different
        return list;
    }

    public static ArrayList<String> getWordsForCategory(String category) {
        if (category.equals(CAT_RANDOM)) {
            // Combine all categories into one massive list
            Set<String> allWords = new HashSet<>();
            for (List<String> list : gameData.values()) {
                allWords.addAll(list);
            }
            ArrayList<String> randomList = new ArrayList<>(allWords);
            Collections.shuffle(randomList);
            return randomList;
        }

        if (gameData.containsKey(category)) {
            // Return a copy so we can shuffle it without affecting the master list
            ArrayList<String> list = new ArrayList<>(gameData.get(category));
            Collections.shuffle(list);
            return list;
        }
        return new ArrayList<>();
    }
